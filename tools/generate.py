#!/usr/bin/env python3
"""Generate Goose bindings and c_headers adapters from rlparser's JSON output."""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SCALARS = {
    "void": ("void", "void"), "bool": ("bool", "uint8_t"),
    "char": ("u8", "uint8_t"), "unsigned char": ("u8", "uint8_t"),
    "short": ("i16", "int16_t"), "unsigned short": ("u16", "uint16_t"),
    "int": ("i32", "int32_t"), "unsigned int": ("u32", "uint32_t"),
    "long": ("i64", "int64_t"), "unsigned long": ("u64", "uint64_t"),
    "float": ("f32", "float"), "double": ("f64", "double"),
}
KEYWORDS = set("fn let var const type struct enum namespace import from in for while if else return match case default out ref store reusable own thread_fn defer guard loop as is true false void bool".split())
# Only these pointers mean one borrowed struct, never an array or retained pointer.
REFS = {
    "UpdateCamera": {"camera"}, "UpdateCameraPro": {"camera"},
    "UploadMesh": {"mesh"}, "GenTextureMipmaps": {"texture"},
    "SetMaterialTexture": {"material"}, "SetModelMeshMaterial": {"model"},
    "WaveCrop": {"wave"}, "WaveFormat": {"wave"},
    "Vector3OrthoNormalize": {"v1", "v2"},
    "MatrixDecompose": {"translation", "rotation", "scale"},
    "QuaternionToAxisAngle": {"outAxis", "outAngle"},
}
DOC_EXAMPLES = {
    "get_color": 'let c = raylib::get_color(0x12345678);\nassert(c.r == 18 && c.g == 52 && c.b == 86 && c.a == 120);',
    "vector2_add": 'let v = raylib::vector2_add(raylib::Vector2 { 2.0, -3.0 }, raylib::Vector2 { 5.0, 11.0 });\nassert(v.x == 7.0 && v.y == 8.0);',
    "check_collision_recs": 'assert(raylib::check_collision_recs(raylib::Rectangle { 0.0, 0.0, 4.0, 3.0 }, raylib::Rectangle { 3.0, 2.0, 5.0, 7.0 }));',
    "gen_image_color": 'let image = raylib::gen_image_color(3, 2, raylib::RED);\ndefer raylib::unload_image(image);\nassert(image.width == 3 && image.height == 2);\nassert(raylib::get_image_color(image, 2, 1) == raylib::RED);',
    "text_format": 'assert(raylib::text_format("literal %s 100%") == "literal %s 100%");',
}


def snake(name):
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).lower()
    # Keep raylib's dimension suffix together: begin_mode_2d, vector2_add.
    name = re.sub(r"([23])_d\b", r"\1d", name)
    return name + "_" if name in KEYWORDS else name


def parse_api(directory):
    binary = directory / "rlparser"
    subprocess.run([os.environ.get("CC", "clang"), "-O2", str(ROOT / "tools/rlparser.c"), "-o", str(binary)], check=True)
    apis = []
    for module, marker in (("raylib", "RLAPI"), ("raymath", "RMAPI")):
        dest = directory / f"{module}.json"
        subprocess.run([str(binary), "-i", str(ROOT / f"vendor/raylib/src/{module}.h"), "-d", marker, "-f", "JSON", "-o", str(dest)], check=True, stdout=subprocess.DEVNULL)
        apis.append(json.loads(dest.read_text()))
    return apis


def generate(apis):
    structs, aliases = {}, {}
    for api in apis:
        for s in api["structs"]:
            structs.setdefault(s["name"], s)
        for a in api["aliases"]:
            # rlparser places '*' in the alias name for pointer typedefs.
            aliases[a["name"].lstrip("*")] = a["type"] + " *" * (len(a["name"]) - len(a["name"].lstrip("*")))
    callbacks = {c["name"] for api in apis for c in api["callbacks"]}

    def resolve(t):
        t = t.removeprefix("const ").strip()
        while t in aliases:
            t = aliases[t]
        return t

    def pointer(t):
        return "*" in resolve(t)

    def gt(t):
        t = resolve(t)
        if "[" in t:
            base, count = re.fullmatch(r"(.+)\[(\d+)\]", t).groups()
            return f"{gt(base)}[{count}]"
        if pointer(t):
            return "u64"
        if t in structs:
            return {"float3": "Float3", "float16": "Float16"}.get(t, t)
        return SCALARS[t][0]

    def ct(t):
        t = resolve(t)
        if "[" in t:
            base, count = re.fullmatch(r"(.+)\[(\d+)\]", t).groups()
            suffix = ct(base) if resolve(base) in structs else gt(base)
            return f"a{count}_{suffix}"
        if pointer(t):
            return "uint64_t"
        if t in structs:
            return f"raylib_{gt(t)}_g6"
        return SCALARS[t][1]

    def convert(t, expression, to_c):
        t = resolve(t)
        if pointer(t):
            return f"({t})(uintptr_t)({expression})" if to_c else f"(uint64_t)(uintptr_t)({expression})"
        if t in structs:
            return f"grl_{'to' if to_c else 'from'}_{t}({expression})"
        return expression

    goose = ["// Generated by tools/generate.py. Edit the generator, not this file.",
             "// Pointer fields and *_raw calls are unsafe native addresses. See README.md.",
             "namespace raylib;", "import std;", "import ffi;", ""]
    abi = ["// Generated packed Goose ABI for the separately compiled TinyCC exports.",
           "#ifndef GOOSE_RAYLIB_ABI_H", "#define GOOSE_RAYLIB_ABI_H", "#include <stdint.h>",
           "#pragma pack(push, 1)", "typedef struct { uint8_t *data; int64_t len; } sl_u8;"]
    h = ["// Generated by tools/generate.py. Uses the compiler's types via c_headers.",
         "#ifndef GOOSE_RAYLIB_H", "#define GOOSE_RAYLIB_H", "#if !defined(__TINYC__)",
         '#include "../vendor/raylib/src/raylib.h"', "#define RAYMATH_STATIC_INLINE",
         '#include "../vendor/raylib/src/raymath.h"', "#include <stdint.h>", "#include <string.h>",
         "#ifndef GRL_INLINE", "#if defined(_MSC_VER)", "#define GRL_INLINE static __forceinline",
         "#else", "#define GRL_INLINE static inline __attribute__((always_inline))", "#endif", "#endif"]
    symbols, emitted, arrays, used_structs = [], set(), set(), set()

    functions = [f for api in apis for f in api["functions"]]
    # CPU Image* mutators borrow exactly one Image; never retain it.
    for f in functions:
        if f["name"].startswith("Image"):
            REFS[f["name"]] = {p["name"] for p in f.get("params", []) if p["type"] == "Image *"}

    def need(t):
        t = resolve(t)
        if "[" in t:
            need(t.split("[")[0])
        elif t in structs and t not in used_structs:
            used_structs.add(t)
            for field in structs[t]["fields"]:
                need(field["type"])

    for f in functions:
        need(f["returnType"])
        for p in f.get("params", []):
            need(p["type"])
            if p["name"] in REFS.get(f["name"], set()):
                need(p["type"].removesuffix(" *"))

    def emit_struct(name):
        if name in emitted:
            return
        s = structs[name]
        for field in s["fields"]:
            t = resolve(field["type"])
            base = t.split("[")[0]
            if base in structs:
                emit_struct(base)
            if "[" in t and ct(t) not in arrays:
                count = re.search(r"\[(\d+)\]", t)[1]
                abi.append(f"typedef struct {{ {ct(base)} e[{count}]; }} {ct(t)};")
                arrays.add(ct(t))
        emitted.add(name)
        goose.extend(["// " + (s["description"] or f"{name} value."), f"struct {gt(name)} {{"])
        abi.append("typedef struct {")
        for field in s["fields"]:
            n, t = snake(field["name"]), field["type"]
            comment = " // " + field["description"] if field["description"] else ""
            goose.append(f"    {n}: {gt(t)},{comment}")
            abi.append(f"    {ct(t)} {n}_g;")
        goose.extend(["}", ""])
        abi.append(f"}} {ct(name)};")
        symbols.append(f"raylib::{gt(name)}")
        if name not in used_structs:
            return
        for to_c in (True, False):
            dest, source = (name, ct(name)) if to_c else (ct(name), name)
            h.extend([f"GRL_INLINE {dest} grl_{'to' if to_c else 'from'}_{name}({source} value) {{", f"    {dest} result = {{0}};"])
            for field in s["fields"]:
                n, t = field["name"], field["type"]
                cn, gn = f"result.{n}", f"value.{snake(n)}_g"
                if not to_c:
                    cn, gn = f"result.{snake(n)}_g", f"value.{n}"
                if "[" in t:
                    base, count = re.fullmatch(r"(.+)\[(\d+)\]", t).groups()
                    lhs = cn + ("[i]" if to_c else ".e[i]")
                    rhs = gn + (".e[i]" if to_c else "[i]")
                    h.append(f"    for (int i = 0; i < {count}; ++i) {lhs} = {convert(base, rhs, to_c)};")
                else:
                    h.append(f"    {cn} = {convert(t, gn, to_c)};")
            h.extend(["    return result;", "}"])

    for name in structs:
        emit_struct(name)
    for name, target in aliases.items():
        goose.extend([f"// C alias of {target}.", f"type {name} = {gt(target)};", ""])
        symbols.append(f"raylib::{name}")

    constants = set()
    for api in apis:
        for d in api["defines"]:
            name, kind, value = d["name"], d["type"], d["value"]
            if name in constants or kind not in ("COLOR", "INT", "FLOAT", "DOUBLE", "STRING", "FLOAT_MATH"):
                continue
            if kind == "COLOR":
                value = "Color { " + re.search(r"\{(.*)\}", value)[1].strip() + " }"
                typ = "Color"
            elif kind == "STRING":
                value, typ = json.dumps(value), None
            elif kind == "FLOAT_MATH":
                value, typ = value.replace("180.0f", "180.0"), "f32"
            else:
                typ = "i32" if kind == "INT" else "f32"
            goose.extend(["// " + (d["description"] or name), f"let {name}{': ' + typ if typ else ''} = {value};", ""])
            constants.add(name)
        for enum in api["enums"]:
            for v in enum["values"]:
                if v["name"] in constants:
                    continue
                goose.extend(["// " + (v["description"] or enum["name"]), f"let {v['name']}: i32 = {v['value']};", ""])
                constants.add(v["name"])

    skipped, coverage = [], []
    for f in functions:
        name, ret, params = f["name"], f["returnType"], f.get("params", [])
        if any(p["type"] in callbacks for p in params):
            skipped.append((name, "native callback registration; Goose callbacks are not supported"))
            continue
        literal = name in ("TraceLog", "TextFormat")
        if any(p["type"] == "..." for p in params):
            if not literal:
                raise ValueError(f"Unhandled variadic function: {name}")
            params = [p for p in params if p["type"] != "..."]
        public = snake(name)
        has_pointer = pointer(ret) or any(pointer(p["type"]) for p in params)
        raw_name = public + "_raw" if has_pointer else public
        description = f["description"] or name

        def emit_adapter(goose_name, modes, doc, wrapper=False):
            cname = "grl_" + goose_name
            gparams, cparams, args, before, after, wrapped = [], [], [], [], [], []
            for p, mode in zip(params, modes):
                pn, t = snake(p["name"]), p["type"]
                if mode == "text":
                    gtype, ctype = "const u8[:]", "sl_u8"
                    args.append(f"(const char *){pn}.data")
                    wrapped.append(f"    let z_{pn} = str({pn}, \"\\0\");")
                elif mode == "ref":
                    base = t.removeprefix("const ").removesuffix(" *")
                    gtype, ctype = gt(base) + "&", ct(base) + " *"
                    before.append(f"    {ct(base)} packed_{pn}; memcpy(&packed_{pn}, {pn}, sizeof packed_{pn});")
                    before.append(f"    {resolve(base)} native_{pn} = {convert(base, 'packed_' + pn, True)};")
                    args.append("&native_" + pn)
                    after.append(f"    packed_{pn} = {convert(base, 'native_' + pn, False)};")
                    after.append(f"    memcpy({pn}, &packed_{pn}, sizeof packed_{pn});")
                else:
                    gtype, ctype = gt(t), ct(t)
                    args.append(convert(t, pn, True))
                gparams.append(f"{pn}: {gtype}")
                cparams.append(f"{ctype} {pn}")
            callargs = args.copy()
            if literal:
                callargs.insert(1 if name == "TraceLog" else 0, '"%s"')
            call = f"{name}({', '.join(callargs)})"
            h.extend([f"GRL_INLINE {ct(ret)} {cname}({', '.join(cparams) or 'void'}) {{", *before])
            if ret == "void":
                h.append("    " + call + ";")
            else:
                h.append(f"    {ret} result = {call};")
            h.extend(after)
            if ret != "void":
                h.append(f"    return {convert(ret, 'result', False)};")
            h.append("}")
            result = "" if ret == "void" else f" -> {gt(ret)}"
            goose.extend(["// " + doc, f"extern fn {goose_name}({', '.join(gparams)}){result} = \"{cname}\";", ""])
            if not wrapper:
                symbols.append(f"raylib::{goose_name}")
                return
            result = " -> u8[>..]" if ret == "const char *" else result
            goose.append("// " + description)
            if any(mode == "text" for mode in modes):
                goose.append("// Text is copied and NUL-terminated for this call; embedded NUL ends the C string.")
            if ret == "const char *":
                goose.append("// Returns an owned copy, empty when raylib returns NULL.")
            if literal:
                goose.append("// Literal text only, not a variadic printf format. Format values in Goose first.")
            if public in DOC_EXAMPLES:
                goose.extend(["//", "// ```goose", *["// " + l for l in DOC_EXAMPLES[public].splitlines()], "// ```"])
            goose.extend([f"inline fn {public}({', '.join(gparams)}){result} {{", *wrapped])
            call = f"{goose_name}({', '.join(('z_' if mode == 'text' else '') + snake(p['name']) for p, mode in zip(params, modes))})"
            if ret == "const char *":
                call = "ffi::cstr(" + call + ")"
            goose.extend(["    " + ("return " if ret != "void" else "") + call + ";", "}", ""])
            symbols.append(f"raylib::{public}")

        doc = description
        if has_pointer:
            doc += " Unsafe: addresses must have native C layout, alignment, capacity and lifetime. Follow raylib's ownership rules."
        if public in DOC_EXAMPLES and not has_pointer:
            doc += "\n//\n// ```goose\n" + "\n".join("// " + l for l in DOC_EXAMPLES[public].splitlines()) + "\n// ```"
        emit_adapter(raw_name, ["raw"] * len(params), doc)
        friendly = not has_pointer
        if has_pointer:
            modes = []
            for p in params:
                if p["type"] == "const char *":
                    modes.append("text")
                elif p["name"] in REFS.get(name, set()):
                    modes.append("ref")
                elif pointer(p["type"]):
                    break
                else:
                    modes.append("raw")
            else:
                if not pointer(ret) or ret == "const char *":
                    emit_adapter("_c_" + public, modes, "Internal adapter; text arguments must include their trailing NUL.", wrapper=True)
                    friendly = True
        coverage.append((name, public if friendly else raw_name, friendly))

    abi.extend(["#pragma pack(pop)", "#endif", ""])
    h.extend(["#undef GRL_INLINE", "#endif", "#endif", ""])
    report = ["# Binding coverage", "", "Generated from the vendored raylib and raymath headers. Regenerate with `python3 tools/generate.py`.", "", f"{len(coverage)} functions bound; {sum(c[2] for c in coverage)} have a pointer-free or borrowed-reference/text interface.", "", "`*_raw` functions use unsafe native addresses, not Goose struct/array addresses. Const C strings have owned-copy wrappers. Callback registration is omitted; variadic text calls take literal text only.", "", "## Omitted", "", *[f"- `{n}`: {reason}." for n, reason in skipped], "", "## Functions", "", "| C | Goose |", "| --- | --- |", *[f"| `{c}` | `raylib::{g}` |" for c, g, _ in coverage], ""]
    return {"raylib.goose": "\n".join(goose), "include/raylib.h": "\n".join(h), "include/abi.h": "\n".join(abi), "api.txt": "\n".join(dict.fromkeys(symbols)) + "\n", "COVERAGE.md": "\n".join(report)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="goose-raylib-generate-") as temp:
        outputs = generate(parse_api(Path(temp)))
    for name, text in outputs.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"Stale generated file: {name}")
        else:
            path.write_text(text)
    print("Generated bindings are current" if args.check else "Generated Goose bindings, inline adapters, native ABI, and coverage")


if __name__ == "__main__":
    main()
